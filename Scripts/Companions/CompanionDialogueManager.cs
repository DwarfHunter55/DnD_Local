    /// <summary>
    /// Creates a fallback dialogue result with a random generic line.
    /// </summary>
    private DialogueResult MakeFallback(string speakerName, FallbackCategory category)
    {
        var lines = FallbackLines[category];
        string line = lines[_rng.Next(lines.Length)];

        return new DialogueResult
        {
            Speaker = speakerName,
            Text = line,
            Mood = string.Empty,
            IsFallback = true
        };
    }

    /// <summary>
    /// Creates a fallback banter exchange between two companions.
    /// </summary>
    private List<DialogueResult> MakeBanterFallback(string name1, string name2)
    {
        var banterLines = FallbackLines[FallbackCategory.Banter];
        int idx1 = _rng.Next(banterLines.Length);
        int idx2;
        do { idx2 = _rng.Next(banterLines.Length); } while (idx2 == idx1 && banterLines.Length > 1);

        return new List<DialogueResult>
        {
            new DialogueResult
            {
                Speaker = name1,
                Text = banterLines[idx1],
                Mood = string.Empty,
                IsFallback = true
            },
            new DialogueResult
            {
                Speaker = name2,
                Text = banterLines[idx2],
                Mood = string.Empty,
                IsFallback = true
            }
        };
    }
